/// Состояние экрана со списком постов.
enum PostsStatus {
  /// Первая загрузка: данных ещё нет.
  loading,

  /// Данные получены с сервера и показаны.
  success,

  /// Загрузка не удалась и показать нечего.
  error,

  /// Показаны сохранённые данные (сервер недоступен или идёт обновление).
  cached,

  /// Постов нет или поиск ничего не нашёл.
  empty,
}